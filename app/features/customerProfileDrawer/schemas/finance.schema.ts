import {z} from 'zod';

const shippingAddressSchema = z.object({
  name: z.string(),
  address: z.string(),
  siteNumber: z.string(),
  billToNumber: z.string(),
  inactive: z.boolean().optional(),
});

export const financeAccountSchema = z.object({
  customerNumber: z.string(),
  organizationNumber: z.string(),
  collector: z.string(),
  status: z.enum(['approved', 'pending', 'on_hold']),
  approvedBy: z.string(),
  approvedDate: z.string(),
  hold: z.object({onHold: z.boolean(), reason: z.string(), since: z.string()}),
  credit: z.object({
    bureau: z.string(),
    grade: z.string(),
    risk: z.string(),
    suggested: z.number(),
    pulled: z.string(),
    requested: z.number(),
    approved: z.number(),
    used: z.number(),
    orderLimit: z.number(),
    available: z.number(),
  }),
  terms: z.string(),
  tier: z.string(),
  paymentMethods: z.array(z.string()),
  tax: z.object({
    exempt: z.boolean(),
    cert: z.string(),
    expires: z.string(),
    ein: z.string(),
  }),
  invoiceDelivery: z.string(),
  invoiceEmail: z.string(),
  profile: z.object({
    rating: z.string(),
    classification: z.string(),
    reviewCycle: z.string(),
    accountStatus: z.string(),
    riskCode: z.string(),
    tolerancePct: z.number(),
    creditCheck: z.boolean(),
    creditHold: z.boolean(),
    overrideTerms: z.boolean(),
    discountGraceDays: z.number(),
    receiptGraceDays: z.number(),
    autoCashRule: z.string(),
  }),
  charges: z.object({
    interestRatePct: z.number(),
    maxInterest: z.number(),
    minStatement: z.number(),
    minDunning: z.number(),
    minReceipt: z.number(),
    minCustBalForCharges: z.number(),
  }),
  classification: z.object({
    customerType: z.string(),
    customerClass: z.string(),
    profileClass: z.string(),
  }),
  billingAddresses: z.object({count: z.number()}),
  shippingAddresses: z.array(shippingAddressSchema),
  ar: z.object({
    current: z.number(),
    pastDue1To30: z.number(),
    pastDue31To60: z.number(),
    pastDue61Plus: z.number(),
    outstanding: z.number(),
    onAccountCash: z.number(),
    onAccountCredits: z.number(),
    unappliedCash: z.number(),
    receiptsAtRisk: z.number(),
    customerBalance: z.number(),
  }),
  requests: z.object({openCount: z.number()}),
});
